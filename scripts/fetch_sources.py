#!/usr/bin/env python3
"""Download the source files the repository uses but does not carry.

`data/sources/sources.toml` lists them: Wikimedia dumps, archive.org scans and
OCR, Kaikki extracts, Apertium and other git checkouts, page images, files
rebuilt by a script, and files that may not be published at all. Everything
else under `data/sources/`, `data/bible/`, `data/conjugation/` and `data/words/`
is in git.

    python3 scripts/fetch_sources.py status             # what is here, what is missing
    python3 scripts/fetch_sources.py fetch              # download everything missing
    python3 scripts/fetch_sources.py fetch xmls/ 'data/sources/glossaries/gsc/*'
    python3 scripts/fetch_sources.py verify             # re-hash what is on disk
    python3 scripts/fetch_sources.py gitignore          # rewrite the ignore block from sources.toml
    python3 scripts/fetch_sources.py stub data/sources/glossaries/xx/raw/scan.pdf   # an entry to paste

A pinned URL that has gone (Wikimedia keeps a dated dump for a few months)
falls back to the entry's `fallback`, usually the `latest` dump: that copy
differs from the one the extracts were made from, so its checksum is not
checked and the run says so.
"""

from __future__ import annotations

import argparse
import bz2
import fnmatch
import gzip
import hashlib
import re
import shutil
import subprocess
import sys
import time
import tomllib
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "data" / "sources" / "sources.toml"
GITIGNORE = ROOT / ".gitignore"
BEGIN = "# BEGIN generated by scripts/fetch_sources.py gitignore: files listed in data/sources/sources.toml"
END = "# END generated"
USER_AGENT = "vulgultra-research/0.1 (+https://github.com/juleshenry/vulgultra; noncommercial lexical sourcing)"
CHUNK = 1 << 20


def load() -> dict:
    with MANIFEST.open("rb") as handle:
        return tomllib.load(handle)


def page_files(entry: dict) -> list[tuple[Path, str]]:
    """Each page of a `[[pages]]` entry as (local path, URL)."""
    return [(ROOT / entry["dir"] / entry["name"].format(n=n), entry["url"].format(n=n)) for n in entry["n"]]


def wanted(path: str, patterns: list[str]) -> bool:
    """Whether a manifest path matches one of the command-line patterns (glob or leading directory)."""
    return not patterns or any(fnmatch.fnmatch(path, p) or path.startswith(p.rstrip("*")) for p in patterns)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(CHUNK), b""):
            digest.update(block)
    return digest.hexdigest()


def human(size: float) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if size < 1000 or unit == "GB":
            return f"{size:.0f} {unit}" if unit == "B" else f"{size:.1f} {unit}"
        size /= 1000
    return f"{size:.1f} GB"


def download(url: str, target: Path) -> None:
    """Stream `url` to `target`, resuming a `.part` file left by an earlier run."""
    part = target.with_name(target.name + ".part")
    target.parent.mkdir(parents=True, exist_ok=True)
    have = part.stat().st_size if part.exists() else 0
    headers = {"User-Agent": USER_AGENT}
    if have:
        headers["Range"] = f"bytes={have}-"
    request = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(request, timeout=120) as response:
        # A server that ignores Range sends the whole file again.
        mode = "ab" if have and response.status == 206 else "wb"
        total = int(response.headers.get("Content-Length") or 0) + (have if mode == "ab" else 0)
        done, last = (have if mode == "ab" else 0), 0.0
        with part.open(mode) as handle:
            for block in iter(lambda: response.read(CHUNK), b""):
                handle.write(block)
                done += len(block)
                if sys.stderr.isatty() and time.time() - last > 0.5:
                    last = time.time()
                    shown = f"{human(done)} of {human(total)}" if total else human(done)
                    print(f"\r    {shown}   ", end="", file=sys.stderr)
    if sys.stderr.isatty():
        print("\r" + " " * 40 + "\r", end="", file=sys.stderr)
    part.replace(target)


def unpack(packed: Path, target: Path, kind: str) -> None:
    opener = {"bz2": bz2.open, "gz": gzip.open}[kind]
    part = target.with_name(target.name + ".part")
    with opener(packed, "rb") as source, part.open("wb") as sink:
        shutil.copyfileobj(source, sink, CHUNK)
    part.replace(target)
    packed.unlink()


def fetch_file(entry: dict, verify: bool) -> str:
    """Bring one `[[file]]` entry to disk; return a one-word outcome."""
    target = ROOT / entry["path"]
    if target.exists() and (not entry.get("size") or target.stat().st_size == entry["size"]):
        if not verify or not entry.get("sha256") or sha256(target) == entry["sha256"]:
            return "present"
        print(f"  checksum differs, fetching again: {entry['path']}")
    kind = entry.get("unpack")
    staging = target.with_name(target.name + "." + kind) if kind else target
    used, fell_back = None, False
    for url in [entry["url"], *entry.get("mirrors", []), entry.get("fallback")]:
        if not url:
            continue
        try:
            print(f"  {entry['path']}\n    <- {url}")
            download(url, staging)
            used = url
            break
        except (urllib.error.URLError, TimeoutError, ConnectionError) as error:
            print(f"    failed: {error}")
            fell_back = True
    if used is None:
        return "failed"
    if kind:
        unpack(staging, target, kind)
    if used == entry.get("fallback") and fell_back:
        print("    fetched the fallback: newer than the copy the extracts were made from; checksum not checked")
        return "fallback"
    if entry.get("sha256") and sha256(target) != entry["sha256"]:
        if entry.get("stable", True):
            print("    checksum differs from sources.toml")
            return "mismatch"
        print("    checksum differs: this source changes over time (stable = false)")
    return "fetched"


def fetch_pages(entry: dict) -> str:
    missing = [(path, url) for path, url in page_files(entry) if not path.exists()]
    for path, url in missing:
        print(f"  {path.relative_to(ROOT)}\n    <- {url}")
        try:
            download(url, path)
        except (urllib.error.URLError, TimeoutError, ConnectionError) as error:
            print(f"    failed: {error}")
            return "failed"
        time.sleep(1)  # archive.org renders each page on request
    return "fetched" if missing else "present"


def fetch_git(entry: dict) -> str:
    target = ROOT / entry["path"]
    if (target / ".git").exists():
        head = subprocess.run(["git", "-C", str(target), "rev-parse", "HEAD"], capture_output=True, text=True)
        if head.stdout.strip() == entry["rev"]:
            return "present"
        print(f"  {entry['path']}: checked out at {head.stdout.strip()[:10]}, sources.toml pins {entry['rev'][:10]}")
        return "mismatch"
    print(f"  {entry['path']}\n    <- {entry['url']} @ {entry['rev'][:10]}")
    target.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["git", "clone", "--quiet", entry["url"], str(target)], check=True)
    subprocess.run(["git", "-C", str(target), "checkout", "--quiet", entry["rev"]], check=True)
    return "fetched"


def status(manifest: dict, patterns: list[str], verify: bool) -> None:
    counts: dict[str, int] = {}
    missing: list[str] = []
    missing_size = 0

    def note(state: str, path: str, size: int = 0) -> None:
        nonlocal missing_size
        counts[state] = counts.get(state, 0) + 1
        if state != "present":
            missing.append(f"  {state:9s} {path}")
            missing_size += size

    for entry in manifest.get("file", []):
        if not wanted(entry["path"], patterns):
            continue
        target = ROOT / entry["path"]
        if not target.exists():
            note("missing", entry["path"], entry.get("size", 0))
        elif entry.get("size") and target.stat().st_size != entry["size"]:
            note("differs", entry["path"])
        elif verify and entry.get("sha256") and sha256(target) != entry["sha256"]:
            note("differs", entry["path"])
        else:
            note("present", entry["path"])
    for entry in manifest.get("pages", []):
        if wanted(entry["dir"], patterns):
            absent = sum(not path.exists() for path, _ in page_files(entry))
            note("missing" if absent else "present", f"{entry['dir']}/ ({absent} of {len(entry['n'])} pages)")
    for entry in manifest.get("git", []):
        if wanted(entry["path"], patterns):
            note("present" if (ROOT / entry["path"] / ".git").exists() else "missing", entry["path"])
    for entry in manifest.get("derived", []):
        if wanted(entry["path"], patterns):
            note("present" if (ROOT / entry["path"]).exists() else "rebuild", entry["path"])
    for entry in manifest.get("local", []):
        if wanted(entry["path"], patterns):
            note("present" if (ROOT / entry["path"]).exists() else "by hand", entry["path"])
    print("\n".join(missing))
    print(", ".join(f"{n} {state}" for state, n in sorted(counts.items())),
          f"({human(missing_size)} to download)" if missing_size else "")


def fetch(manifest: dict, patterns: list[str], verify: bool) -> int:
    outcomes: dict[str, int] = {}
    for entry in manifest.get("file", []):
        if wanted(entry["path"], patterns):
            outcome = fetch_file(entry, verify)
            outcomes[outcome] = outcomes.get(outcome, 0) + 1
    for entry in manifest.get("pages", []):
        if wanted(entry["dir"], patterns):
            outcome = fetch_pages(entry)
            outcomes[outcome] = outcomes.get(outcome, 0) + 1
    for entry in manifest.get("git", []):
        if wanted(entry["path"], patterns):
            outcome = fetch_git(entry)
            outcomes[outcome] = outcomes.get(outcome, 0) + 1
    rebuild = [e for e in manifest.get("derived", []) if wanted(e["path"], patterns) and not (ROOT / e["path"]).exists()]
    if rebuild:
        print("\nRebuilt by a script, not downloaded:")
        for command in dict.fromkeys(e["command"] for e in rebuild):
            print(f"  {command}")
    by_hand = [e for e in manifest.get("local", []) if wanted(e["path"], patterns) and not (ROOT / e["path"]).exists()]
    if by_hand:
        print("\nNot published; obtain by hand if you need them:")
        for entry in by_hand:
            print(f"  {entry['path']}\n    {entry['reason']}. {entry.get('obtain', '')}".rstrip())
    print("\n" + ", ".join(f"{n} {state}" for state, n in sorted(outcomes.items())))
    return 1 if outcomes.get("failed") or outcomes.get("mismatch") else 0


def ignore_line(path: str) -> str:
    """An anchored .gitignore pattern matching exactly this path."""
    escaped = "".join("\\" + c if c in "*?[]\\!#" else c for c in path)
    return "/" + escaped.rstrip("/") + ("/" if path.endswith("/") else "")


def gitignore(manifest: dict) -> None:
    lines = [ignore_line(e["path"]) for e in manifest.get("file", [])]
    # Only the images: the OCR written beside them is ours and stays in git.
    lines += [ignore_line(e["dir"] + "/") + re.sub(r"\{[^}]*\}", "*", e["name"]) for e in manifest.get("pages", [])]
    lines += [ignore_line(e["path"] + "/") for e in manifest.get("git", [])]
    lines += [ignore_line(e["path"]) for e in manifest.get("derived", [])]
    lines += [ignore_line(e["path"]) for e in manifest.get("local", [])]
    # Paths under xmls/ and vendor/ are ignored wholesale already.
    lines = sorted({line for line in lines if not line.startswith(("/xmls/", "/vendor/"))})
    block = "\n".join([BEGIN, *lines, END])
    text = GITIGNORE.read_text()
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        text = head + block + rest.split(END, 1)[1]
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    GITIGNORE.write_text(text)
    print(f"{len(lines)} paths in the generated block of {GITIGNORE.relative_to(ROOT)}")


def stub(patterns: list[str]) -> None:
    """Print a `[[file]]` entry, with size and checksum, for each file named."""
    for name in patterns:
        path = (ROOT / name).resolve()
        print(f'[[file]]\npath = "{path.relative_to(ROOT)}"\nurl = ""\nsize = {path.stat().st_size}\n'
              f'sha256 = "{sha256(path)}"\nlicence = ""\nnote = ""\n')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("command", choices=["status", "fetch", "verify", "gitignore", "stub"])
    parser.add_argument("patterns", nargs="*", help="only paths matching these globs or leading directories")
    parser.add_argument("--verify", action="store_true", help="compare checksums, not only sizes (slow for xmls/)")
    arguments = parser.parse_args()
    manifest = load()
    if arguments.command == "status":
        status(manifest, arguments.patterns, arguments.verify)
    elif arguments.command == "verify":
        status(manifest, arguments.patterns, True)
    elif arguments.command == "fetch":
        sys.exit(fetch(manifest, arguments.patterns, arguments.verify))
    elif arguments.command == "stub":
        stub(arguments.patterns)
    else:
        gitignore(manifest)


if __name__ == "__main__":
    main()
